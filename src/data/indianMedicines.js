// Fast client-side fuzzy search
export function searchIndianMedicines(query, limit = 15) {
  if (!query || query.length < 2) return []
  const q = query.toLowerCase().trim()
  const exact = [], starts = [], contains = []
  for (const m of INDIAN_MEDICINES) {
    const b = m.b.toLowerCase()
    const g = m.g.toLowerCase()
    const c = m.c.toLowerCase()
    if (b === q || g.startsWith(q)) exact.push(m)
    else if (b.startsWith(q)) starts.push(m)
    else if (b.includes(q) || g.includes(q) || c.includes(q) || m.m.toLowerCase().includes(q)) contains.push(m)
  }
  return [...exact, ...starts, ...contains].slice(0, limit)
}
